    <section>
      <h2>Proposition de réforme constitutionnelle :<br><small>Déclaration du droit d’accès progressif à la propriété</small></h2>
      <p><em>Ce texte propose d’ajouter à la Constitution un nouveau droit fondamental : celui d’accéder progressivement à la propriété de son logement. Les articles ci-dessous en énoncent les principes généraux, les mécanismes de mise en œuvre, les protections contre les abus et les garanties pour une application équitable.</em></p>
      <ol>
        <li><strong>Article 1 :</strong> Tout citoyen a le droit d’accéder progressivement à la propriété de son logement.</li>
        <li><strong>Article 2 :</strong> Tout contrat d’occupation peut prévoir l’acquisition progressive du bien par l’occupant selon des modalités déterminées par la loi.</li>
        <li><strong>Article 3 :</strong> La gestion, l’entretien et l’organisation de l’accession progressive à la propriété ouvrent droit à une rémunération équitable, proportionnée au service réellement rendu. Aucune rémunération ne peut avoir pour effet de constituer une rente ni d’entraver l’accès équitable à la propriété.</li>
        <li><strong>Article 4 :</strong> L’épargne destinée à l’acquisition progressive peut être temporairement investie dans des projets d’intérêt général, sous réserve de sa restitution garantie au profit de l’occupant.</li>
        <li><strong>Article 5 :</strong> La spéculation sur les biens essentiels, notamment les logements d’habitation, est interdite. La valeur d’acquisition dans le cadre de l’accession progressive est fixée de manière transparente et définitive dès l’origine du contrat.</li>
        <li><strong>Article 6 :</strong> L’État garantit la neutralité, la transparence et la sécurité des opérations d’accession progressive par des mécanismes publics de contrôle, d’enregistrement et de médiation.</li>
        <li><strong>Article 7 :</strong> Les modalités d’application de ces principes sont déterminées par la loi organique <small>(loi de rang supérieur aux lois ordinaires, mais inférieure à la Constitution)</small>.</li>
      </ol>
    </section>

    <section>
      <h2>Propositions d’adaptations législatives<br><small>pour mettre en œuvre ce droit constitutionnel</small></h2>
      <p><em>Cette seconde partie complète la proposition constitutionnelle en présentant des pistes concrètes de traduction dans le droit ordinaire, par des ajustements législatifs, fiscaux ou réglementaires. Elle vise à montrer comment ce droit à l’accession progressive peut être mis en œuvre à partir des cadres existants, via des contrats adaptés, une fiscalité incitative et un encadrement public renforcé.</em></p>
      <h3>1. Code civil</h3>
      <ul>
        <li><strong>Objectif :</strong> intégrer l’accession progressive dans le droit des contrats, de la propriété, et supprimer les rentes abusives.</li>
        <li>
          <strong>a)</strong> Modifier la partie sur les contrats de bail (Articles 1708 et suivants) :
          <ul>
            <li>Ajouter un nouveau type de contrat : "contrat de location-accession progressive".</li>
            <li>Définir un transfert progressif de propriété, sécurisé et enregistré.</li>
          </ul>
        </li>
        <li>
          <strong>b)</strong> Modifier la partie sur la vente (Articles 1582 et suivants) :
          <ul>
            <li>Introduire la notion de vente à transfert progressif.</li>
            <li>Encadrer la fixation du prix dès la conclusion initiale.</li>
          </ul>
        </li>
        <li>
          <strong>c)</strong> Modifier l’article 544 sur la propriété :
          <ul>
            <li>Ajouter un alinéa reconnaissant que la propriété peut être acquise progressivement par l’usage et l’épargne.</li>
          </ul>
        </li>
      </ul>

      <h3>2. Code de la construction et de l'habitation</h3>
      <ul>
        <li><strong>Objectif :</strong> faire évoluer les régimes de location-accession.</li>
        <li>
          <strong>a)</strong> Modifier les articles L.254-1 et suivants :
          <ul>
            <li>Étendre à toutes formes de logements.</li>
            <li>Simplifier l’accès en supprimant les obstacles inutiles.</li>
          </ul>
        </li>
        <li>
          <strong>b)</strong> Créer un titre spécial sur "l'accession progressive sécurisée" :
          <ul>
            <li>Définir les droits et obligations de chaque partie.</li>
            <li>Encadrer l’épargne et les investissements pour des projets utiles, transparents et non spéculatifs.</li>
          </ul>
        </li>
      </ul>

      <h3>3. Code monétaire et financier</h3>
      <ul>
        <li><strong>Objectif :</strong> protéger l’épargne et limiter la spéculation immobilière.</li>
        <li>
          <strong>a)</strong> Réguler l’épargne affectée :
          <ul>
            <li>Créer des comptes bloqués pour accession progressive.</li>
            <li>Interdire la spéculation sur ces fonds.</li>
          </ul>
        </li>
        <li>
          <strong>b)</strong> Limiter les prêts bancaires :
          <ul>
            <li>Interdire les crédits basés uniquement sur la valeur spéculative des biens essentiels.</li>
          </ul>
        </li>
      </ul>

      <h3>4. Code général des impôts</h3>
      <ul>
        <li><strong>Objectif :</strong> orienter fiscalement les comportements vertueux.</li>
        <li>
          <strong>a)</strong> Avantages fiscaux :
          <ul>
            <li>Crédit d’impôt pour les occupants engagés.</li>
            <li>Allègement fiscal pour les vendeurs solidaires.</li>
          </ul>
        </li>
        <li>
          <strong>b)</strong> Taxation des comportements spéculatifs :
          <ul>
            <li>Sur-taxation des plus-values spéculatives hors accession progressive.</li>
          </ul>
        </li>
      </ul>

      <h3>5. Code de la consommation</h3>
      <ul>
        <li><strong>Objectif :</strong> protéger les futurs propriétaires contre les abus.</li>
        <li>
          <strong>a)</strong> Étendre les protections existantes :
          <ul>
            <li>Inclure le contrat d’accession progressive dans le droit de la consommation.</li>
            <li>Renforcer l’obligation d’information et de transparence.</li>
          </ul>
        </li>
        <li>
          <strong>b)</strong> Encadrer les pratiques abusives et les frais cachés :
          <ul>
            <li>Interdire les clauses déséquilibrées dans les contrats d’accession progressive.</li>
            <li>Imposer un plafonnement des frais de gestion ou d'accompagnement.</li>
            <li>Sanctionner toute publicité trompeuse sur ce type de contrat.</li>
          </ul>
        </li>
      </ul>
