<section class="bg-light p-4 rounded shadow-soft mb-4">
  <h2 class="h4 mb-3">Manifeste pour une Constitution Partagée</h2>
  <ol>
    <li><strong>Nous partons d’un constat.</strong>
      <ul>
        <li>La démocratie représentative est à bout de souffle.</li>
        <li>Le contrat social s’effrite.</li>
        <li>Partout, l’unanimisme est exigé, le désaccord disqualifié, la majorité devient un instrument de domination.</li>
        <li>Ceux qui ne pensent pas comme « nous » sont exclus, ridiculisés, ou contraints au silence.</li>
      </ul>
    </li>
    <li><strong>Nous refusons cette logique d’écrasement.</strong>
      <ul>
        <li>Nous ne voulons plus d’un pouvoir qui s’impose par la force du nombre ou le confort du consensus mou.</li>
        <li>Nous ne voulons plus de lois écrites sans nous, pour nous, contre nous.</li>
        <li>Nous ne croyons plus que l’unité suppose l’uniformité.</li>
      </ul>
    </li>
    <li><strong>Nous affirmons un pari.</strong>
      <ul>
        <li>Il est possible de faire coexister des visions irréconciliables dans un même espace politique.</li>
        <li>Il est possible de désobéir sans rompre, de contester sans détruire, de décider sans exclure.</li>
        <li>Nous croyons qu’une République peut être fondée non sur l’adhésion, mais sur la coopération.</li>
        <li>Non sur l’effacement du dissensus, mais sur son organisation.</li>
        <li>Non sur la verticalité du pouvoir, mais sur le conflit fécond.</li>
      </ul>
    </li>
    <li><strong>Nous expérimentons une méthode.</strong>
      <ul>
        <li>Ici, le peuple écrit, amende et valide sa propre loi fondamentale.</li>
        <li>Chaque citoyen peut participer, critiquer, proposer.</li>
        <li>La Constitution n’est plus un texte figé par quelques-uns, mais un chantier vivant, accessible, disputé.</li>
        <li>Nous n’attendons plus d’être représentés : nous nous représentons nous-mêmes.</li>
      </ul>
    </li>
    <li><strong>Nous lançons un appel.</strong>
      <ul>
        <li>À ceux qui se sentent exclus du jeu politique.</li>
        <li>À ceux qui ne se reconnaissent plus dans les partis, ni dans les institutions.</li>
        <li>À ceux qui veulent créer sans dominer, décider sans écraser.</li>
        <li>Rejoignez-nous. Pas pour signer un programme. Mais pour co-construire un terrain commun, où le désaccord ne sera plus un problème à résoudre, mais une condition à organiser.</li>
      </ul>
    </li>
  </ol>
  <p class="fw-semibold mt-3">C’est cela, notre Constitution Partagée.</p>
</section>