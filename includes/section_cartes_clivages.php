<script>
  document.addEventListener('DOMContentLoaded', () => {
    const filtreDomaine = document.getElementById('filtre-domaine');
    const filtreValeur = document.getElementById('filtre-valeur');
    const filtreTexte = document.getElementById('filtre-texte');

    function filtrerCartes() {
      const d = filtreDomaine.value.toLowerCase();
      const v = filtreValeur.value.toLowerCase();
      const t = filtreTexte.value.toLowerCase();
      document.querySelectorAll('.carte-item').forEach(carte => {
        const domaines = carte.dataset.domaines.split(',');
        const valeurs = carte.dataset.valeurs.split(',');
        const keywords = carte.dataset.keywords;
        const matchDomaine = !d || domaines.includes(d);
        const matchValeur = !v || valeurs.includes(v);
        const contenuCarte = carte.innerText.toLowerCase();
        const matchTexte = !t || keywords.includes(t) || contenuCarte.includes(t);
        carte.style.display = (matchDomaine && matchValeur && matchTexte) ? '' : 'none';
      });
    }

    filtreDomaine.addEventListener('change', filtrerCartes);
    filtreValeur.addEventListener('change', filtrerCartes);
    filtreTexte.addEventListener('input', filtrerCartes);

    document.querySelectorAll('.toggle-btn').forEach(button => {
      button.addEventListener('click', () => {
        const details = button.closest('.carte-clivage').querySelector('.carte-details');
        const isVisible = details.style.display === 'block';
        details.style.display = isVisible ? 'none' : 'block';
        button.textContent = isVisible ? 'Explorer' : 'Replier';
      });
    });

    document.querySelectorAll('.export-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const carte = btn.closest('.carte-clivage').outerHTML;
        const blob = new Blob([carte], {
          type: 'text/html'
        });
        const a = document.createElement('a');
        a.href = URL.createObjectURL(blob);
        a.download = 'carte_clivage.html';
        a.click();
      });
    });
  });
</script>